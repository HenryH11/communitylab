"""Contrato DB-API usado por Oracle y sus dobles transaccionales de prueba."""

from types import TracebackType
from typing import Any, Protocol, Self


class CursorDB(Protocol):
    def __enter__(self) -> Self: ...

    def __exit__(
        self, exc_type: type[BaseException] | None,
        exc_value: BaseException | None, traceback: TracebackType | None, /,
    ) -> bool | None: ...

    def execute(self, sql: str, parametros: dict[str, Any] | None = None, /) -> object: ...

    def executemany(self, sql: str, parametros: list[dict[str, Any]], /) -> object: ...

    def fetchall(self) -> list[tuple[Any, ...]]: ...

    def setinputsizes(self, **parametros: Any) -> object: ...


class ConexionDB(Protocol):
    @property
    def autocommit(self) -> bool: ...

    @property
    def transaction_in_progress(self) -> bool: ...

    def cursor(self) -> CursorDB: ...

    def commit(self) -> None: ...

    def rollback(self) -> None: ...
